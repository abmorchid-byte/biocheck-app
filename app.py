@app.route('/')
def home():
    query = request.args.get('q', '').lower().strip()
    selected_cat = request.args.get('cat', 'toutes')
    selected_id = request.args.get('id', None)

    filtered_analyses = ANALYSES_DATA

    if selected_cat != 'toutes':
        filtered_analyses = [a for a in filtered_analyses if a['categorie_id'] == selected_cat]

    if query:
        filtered_analyses = [
            a for a in filtered_analyses 
            if query in a['nom'].lower() or query in a['abreviation'].lower() or query in a['categorie_nom'].lower()
        ]

    selected_analysis = None
    if selected_id:
        selected_analysis = next((a for a in ANALYSES_DATA if a['id'] == selected_id), None)

    return render_template(
        'index.html',
        categories=CATEGORIES,
        analyses=filtered_analyses,
        selected_analysis=selected_analysis,
        selected_cat=selected_cat,
        query=query
    )


